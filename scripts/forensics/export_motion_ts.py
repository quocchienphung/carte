"""Generate src/lib/roco-bank/motion/measured.ts from references/reference-metrics*.json.

Keeps every fitted constant traceable to the forensic data (no hand transcription).
Usage: .venv-tools/bin/python -I scripts/forensics/export_motion_ts.py
"""

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / "references"
m = json.load(open(REF / "reference-metrics.json"))
cards = json.load(open(REF / "reference-metrics-cards.json"))
poster = json.load(open(REF / "tracking/corners_f000.json"))


def pose_from_corners(c: dict, rest_scale_len: float = 440.0) -> dict:
    # centre = mean of BL/BR/TR(/TL); rotation from bottom edge; scale from bottom length
    pts = [c["corners"][k] for k in ("TL", "TR", "BR", "BL") if k in c["corners"]]
    bl, br = np.array(c["corners"]["BL"]), np.array(c["corners"]["BR"])
    tr = np.array(c["corners"]["TR"])
    rot = float(np.degrees(np.arctan2(br[1] - bl[1], br[0] - bl[0])))
    scale = float(np.linalg.norm(br - bl) / rest_scale_len)
    centre = (bl + tr) / 2
    return {"cx": round(float(centre[0]), 2), "cy": round(float(centre[1]), 2), "rot": round(rot, 3), "scale": round(scale, 4)}


early = cards.get("orange_early_blur_opacity", {})
early_rows = sorted((int(k), v["blur"], v["opacity"]) for k, v in early.items())

out = {
    "cardFits": cards["fits"],
    "cardRest": {k: {p: round(v, 3) for p, v in d.items()} for k, d in cards["rest"].items()},
    "cardPoster": {k: pose_from_corners(v) for k, v in poster.items()},
    "orangeFocus": [{"t": round(n / 30, 4), "blur": round(b, 2), "opacity": round(o, 3)} for n, b, o in early_rows],
    "zoom": {k: m["zoom"][k] for k in ("from", "to", "start", "duration", "bezier")},
    "scroll": {k: m["scroll"][k] for k in ("distance", "start", "duration", "bezier", "card_parallax_factor")},
    "morphAtoB": m["bento"]["morph_A_to_B"],
    "morphBtoA": m["bento"]["morph_B_to_A"],
    "tileEntrance": m["bento"]["entrance_scale"]["power_out_fits"],
    "marquee": {k: m["marquee"][k] for k in ("c_px_per_s", "A_px", "k_per_s")},
}

ts = [
    "// GENERATED by scripts/forensics/export_motion_ts.py from references/reference-metrics*.json — do not edit by hand.",
    "",
    "export type Bezier = [number, number, number, number];",
    "export type PropFit = { from: number; to: number; start: number; duration: number; bezier: Bezier; rms: number };",
    "export type CardPose = { cx: number; cy: number; rot: number; scale: number };",
    "",
]
for key, val in out.items():
    ts.append(f"export const {key} = {json.dumps(val, indent=2)} as const;")
    ts.append("")
dst = ROOT / "src/lib/roco-bank/motion/measured.ts"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text("\n".join(ts))
print("wrote", dst, dst.stat().st_size, "bytes")
print(json.dumps(out["cardPoster"], indent=1))
